import { Language } from '../types';

const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toLocalDigits(input: string | number, lang: Language): string {
  const str = String(input);
  if (lang !== 'bn') return str;
  return str.replace(/\d/g, (d) => BN_DIGITS[Number(d)] ?? d);
}

export function formatNum(num: number, lang: Language, decimals = 0): string {
  const fixed = decimals > 0 ? Number(num.toFixed(decimals)).toString() : Math.round(num).toString();
  return toLocalDigits(fixed, lang);
}

export function formatGregorianDate(date: Date, lang: Language): string {
  try {
    return new Intl.DateTimeFormat(lang === 'bn' ? 'bn-BD' : 'en-GB', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    }).format(date);
  } catch {
    return toLocalDigits(date.toISOString().slice(0, 10), lang);
  }
}

export function formatTime12h(date: Date, lang: Language): string {
  try {
    return new Intl.DateTimeFormat(lang === 'bn' ? 'bn-BD' : 'en-US', {
      hour: '2-digit',
      minute: '2-digit',
      hour12: true,
    }).format(date);
  } catch {
    const h = date.getHours();
    const m = String(date.getMinutes()).padStart(2, '0');
    const h12 = h % 12 || 12;
    return toLocalDigits(`${h12}:${m}`, lang);
  }
}

export function formatHHMM(hhmm: string, lang: Language): string {
  if (!hhmm || !hhmm.includes(':')) return toLocalDigits(hhmm || '', lang);
  const [hStr, mStr] = hhmm.split(':');
  const d = new Date();
  d.setHours(Number(hStr) || 0, Number(mStr) || 0, 0, 0);
  return formatTime12h(d, lang);
}

